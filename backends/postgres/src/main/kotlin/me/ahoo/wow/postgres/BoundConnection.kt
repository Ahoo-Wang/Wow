package me.ahoo.wow.postgres

import java.lang.reflect.InvocationHandler
import java.lang.reflect.InvocationTargetException
import java.lang.reflect.Method
import java.lang.reflect.Proxy
import java.sql.Connection
import java.sql.PreparedStatement
import java.sql.SQLException
import java.sql.Statement

/**
 * A transaction's connection whose first statement also carries the transaction's [settings] (`SET LOCAL`, `SET
 * TRANSACTION READ ONLY`), in the same round trip: the statement's text is the settings, then the statement, which
 * pgjdbc sends as one message. A caller sees plain JDBC: `executeQuery`, `executeUpdate` and `execute` step past the
 * settings' results to the statement's own.
 *
 * pgjdbc cannot batch a statement of several statements, so a first statement that batches (`addBatch`) sends the
 * settings on their own first, as one round trip more, and batches the statement alone; so does any other way of
 * making a statement than [prepareStatement] or [createStatement] with no options. Every later statement is the
 * connection's own.
 */
internal class BoundConnection(
    private val delegate: Connection,
    settings: List<String>,
) : Connection by delegate {
    private val prefix = settings.joinToString("") { "$it; " }
    private val skipped = settings.size

    /** The settings on their own, for a statement that cannot carry them. */
    private val alone = settings.joinToString("; ")

    /** Whether the settings are still to be sent: with the first statement, or on their own before another. */
    private var pending = settings.isNotEmpty()

    /** Sends the settings on their own, once, before a statement that cannot carry them. */
    private fun settle() {
        if (!pending) return
        pending = false
        delegate.createStatement().use { it.execute(alone) }
    }

    override fun prepareStatement(sql: String): PreparedStatement {
        if (!pending) return delegate.prepareStatement(sql)
        pending = false
        val handler = PreparedHandler(sql)
        return Proxy.newProxyInstance(LOADER, arrayOf(PreparedStatement::class.java), handler) as PreparedStatement
    }

    override fun createStatement(): Statement {
        if (!pending) return delegate.createStatement()
        pending = false
        val handler = StatementHandler(delegate.createStatement())
        return Proxy.newProxyInstance(LOADER, arrayOf(Statement::class.java), handler) as Statement
    }

    override fun prepareStatement(sql: String, autoGeneratedKeys: Int): PreparedStatement =
        settled { delegate.prepareStatement(sql, autoGeneratedKeys) }

    override fun prepareStatement(sql: String, columnIndexes: IntArray): PreparedStatement =
        settled { delegate.prepareStatement(sql, columnIndexes) }

    override fun prepareStatement(sql: String, columnNames: Array<out String>): PreparedStatement =
        settled { delegate.prepareStatement(sql, columnNames) }

    override fun prepareStatement(sql: String, resultSetType: Int, resultSetConcurrency: Int): PreparedStatement =
        settled { delegate.prepareStatement(sql, resultSetType, resultSetConcurrency) }

    override fun prepareStatement(
        sql: String,
        resultSetType: Int,
        resultSetConcurrency: Int,
        resultSetHoldability: Int,
    ): PreparedStatement = settled {
        delegate.prepareStatement(
            sql,
            resultSetType,
            resultSetConcurrency,
            resultSetHoldability
        )
    }

    override fun createStatement(resultSetType: Int, resultSetConcurrency: Int): Statement =
        settled { delegate.createStatement(resultSetType, resultSetConcurrency) }

    override fun createStatement(resultSetType: Int, resultSetConcurrency: Int, resultSetHoldability: Int): Statement =
        settled { delegate.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability) }

    override fun prepareCall(sql: String) = settled { delegate.prepareCall(sql) }

    override fun prepareCall(sql: String, resultSetType: Int, resultSetConcurrency: Int) =
        settled { delegate.prepareCall(sql, resultSetType, resultSetConcurrency) }

    override fun prepareCall(sql: String, resultSetType: Int, resultSetConcurrency: Int, resultSetHoldability: Int) =
        settled { delegate.prepareCall(sql, resultSetType, resultSetConcurrency, resultSetHoldability) }

    private inline fun <T> settled(make: () -> T): T {
        settle()
        return make()
    }

    override fun <T : Any?> unwrap(iface: Class<T>): T =
        if (iface.isInstance(this)) iface.cast(this) else delegate.unwrap(iface)

    override fun isWrapperFor(iface: Class<*>): Boolean = iface.isInstance(this) || delegate.isWrapperFor(iface)

    /** Steps past the settings' results of [statement]'s last execution; whether the statement's own is a result set. */
    private fun ownResult(statement: Statement, first: Boolean): Boolean {
        var isResultSet = first
        repeat(skipped) { isResultSet = statement.moreResults }
        return isResultSet
    }

    /** What [name], an execution of [statement] whose own result [isResultSet] tells, answers its caller. */
    private fun answer(name: String, statement: Statement, isResultSet: Boolean): Any? = when (name) {
        "executeQuery" -> if (isResultSet) statement.resultSet else throw SQLException(NO_RESULT)
        "executeUpdate", "executeLargeUpdate" -> {
            if (isResultSet) throw SQLException(A_RESULT)
            if (name == "executeUpdate") statement.updateCount else statement.largeUpdateCount
        }
        else -> isResultSet
    }

    private fun forward(target: Any, method: Method, args: Array<out Any?>?): Any? = try {
        method.invoke(target, *(args ?: emptyArray()))
    } catch (failure: InvocationTargetException) {
        throw failure.targetException
    }

    /**
     * The first prepared statement: prepared with the settings until a batch needs it alone. What is set on it (its
     * parameters, its fetch size) is kept until then, so the statement prepared alone gets it as it was.
     */
    private inner class PreparedHandler(private val sql: String) : InvocationHandler {
        private var target: PreparedStatement = delegate.prepareStatement(prefix + sql)
        private var carrying = true

        /** What was set on the statement: the last value of each setter and parameter, in the order set. */
        private val settings = LinkedHashMap<Pair<String, Any?>, Pair<Method, Array<out Any?>?>>()

        override fun invoke(proxy: Any, method: Method, args: Array<out Any?>?): Any? {
            val name = method.name
            return when {
                !carrying -> forward(target, method, args)
                name in EXECUTIONS && args.isNullOrEmpty() -> answer(name, target, ownResult(target, target.execute()))
                name == "addBatch" -> {
                    alone()
                    forward(target, method, args)
                }
                else -> forward(target, method, args).also { remember(name, method, args) }
            }
        }

        /** Keeps what [method] set on the statement, for [alone]; `clearParameters` forgets it. */
        private fun remember(name: String, method: Method, args: Array<out Any?>?) {
            when {
                name == "clearParameters" -> settings.clear()
                name.startsWith("set") -> {
                    // A parameter's setter keys by its index, a statement option's by its name alone.
                    val key = name to args?.takeIf { method.parameterCount > 1 }?.firstOrNull()
                    settings.remove(key)
                    settings[key] = method to args
                }
            }
        }

        /** Gives up carrying the settings: sends them on their own, and prepares the statement alone. */
        private fun alone() {
            carrying = false
            target.close()
            delegate.createStatement().use { it.execute(alone) }
            target = delegate.prepareStatement(sql)
            settings.values.forEach { (method, args) -> forward(target, method, args) }
            settings.clear()
        }
    }

    /**
     * The first plain statement: its first execution of one statement carries the settings; a batch, or an execution
     * with options, sends them on their own first.
     */
    private inner class StatementHandler(private val target: Statement) : InvocationHandler {
        private var carrying = true

        override fun invoke(proxy: Any, method: Method, args: Array<out Any?>?): Any? {
            val name = method.name
            if (carrying && (name.startsWith("execute") || name == "addBatch")) {
                carrying = false
                val sql = args?.singleOrNull() as? String
                if (sql != null && name in EXECUTIONS) {
                    return answer(name, target, ownResult(target, target.execute(prefix + sql)))
                }
                target.execute(alone)
            }
            return forward(target, method, args)
        }
    }

    private companion object {
        val LOADER: ClassLoader = BoundConnection::class.java.classLoader

        /** The executions that carry the settings, and step past their results to the statement's own. */
        val EXECUTIONS = setOf("execute", "executeQuery", "executeUpdate", "executeLargeUpdate")

        /** pgjdbc's own words for a query that returned no rows' result, and an update that returned one. */
        const val NO_RESULT = "No results were returned by the query."
        const val A_RESULT = "A result was returned when none was expected."
    }
}
