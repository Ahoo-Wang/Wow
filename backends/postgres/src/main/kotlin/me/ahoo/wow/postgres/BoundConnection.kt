package me.ahoo.wow.postgres

import me.ahoo.wow.postgres.PostgresTimeouts.TransactionBound
import java.sql.CallableStatement
import java.sql.Connection
import java.sql.PreparedStatement
import java.sql.ResultSet
import java.sql.SQLException
import java.sql.Statement

/**
 * A transaction's connection whose first statement also carries the transaction's [bound] (`SET LOCAL`, `SET
 * TRANSACTION READ ONLY`), in the same round trip: the statement's text is the bound, then the statement, which pgjdbc
 * sends as one message. A caller sees plain JDBC: an execution steps past the bound's results to the statement's own.
 *
 * pgjdbc cannot batch a statement of several statements, so a first prepared statement refuses to batch
 * ([IllegalStateException]): a store that needs a batch first sends a statement of its own before it, which carries
 * the bound. A first plain statement that batches, an execution with options, and any other way of making a statement
 * send the bound on their own first. Every later statement is the connection's own.
 */
internal class BoundConnection(
    private val delegate: Connection,
    private val bound: TransactionBound,
) : Connection by delegate {
    /** Whether the bound is still to be sent: with the first statement, or on its own before another. */
    private var pending = true

    /** Sends the bound on its own, once, before a statement that cannot carry it. */
    private fun settle() {
        if (!pending) return
        pending = false
        delegate.createStatement().use { it.execute(bound.alone) }
    }

    override fun prepareStatement(sql: String): PreparedStatement {
        if (!pending) return delegate.prepareStatement(sql)
        pending = false
        return BoundPreparedStatement(delegate.prepareStatement(bound.prefix + sql))
    }

    override fun createStatement(): Statement {
        if (!pending) return delegate.createStatement()
        pending = false
        return BoundStatement(delegate.createStatement())
    }

    override fun prepareStatement(sql: String, autoGeneratedKeys: Int): PreparedStatement {
        settle()
        return delegate.prepareStatement(sql, autoGeneratedKeys)
    }

    override fun prepareStatement(sql: String, columnIndexes: IntArray): PreparedStatement {
        settle()
        return delegate.prepareStatement(sql, columnIndexes)
    }

    override fun prepareStatement(sql: String, columnNames: Array<out String>): PreparedStatement {
        settle()
        return delegate.prepareStatement(sql, columnNames)
    }

    override fun prepareStatement(sql: String, resultSetType: Int, resultSetConcurrency: Int): PreparedStatement {
        settle()
        return delegate.prepareStatement(sql, resultSetType, resultSetConcurrency)
    }

    override fun prepareStatement(
        sql: String,
        resultSetType: Int,
        resultSetConcurrency: Int,
        resultSetHoldability: Int,
    ): PreparedStatement {
        settle()
        return delegate.prepareStatement(sql, resultSetType, resultSetConcurrency, resultSetHoldability)
    }

    override fun createStatement(resultSetType: Int, resultSetConcurrency: Int): Statement {
        settle()
        return delegate.createStatement(resultSetType, resultSetConcurrency)
    }

    override fun createStatement(resultSetType: Int, resultSetConcurrency: Int, resultSetHoldability: Int): Statement {
        settle()
        return delegate.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability)
    }

    override fun prepareCall(sql: String): CallableStatement {
        settle()
        return delegate.prepareCall(sql)
    }

    override fun prepareCall(sql: String, resultSetType: Int, resultSetConcurrency: Int): CallableStatement {
        settle()
        return delegate.prepareCall(sql, resultSetType, resultSetConcurrency)
    }

    override fun prepareCall(
        sql: String,
        resultSetType: Int,
        resultSetConcurrency: Int,
        resultSetHoldability: Int,
    ): CallableStatement {
        settle()
        return delegate.prepareCall(sql, resultSetType, resultSetConcurrency, resultSetHoldability)
    }

    override fun <T : Any?> unwrap(iface: Class<T>): T =
        if (iface.isInstance(this)) iface.cast(this) else delegate.unwrap(iface)

    override fun isWrapperFor(iface: Class<*>): Boolean = iface.isInstance(this) || delegate.isWrapperFor(iface)

    /** Steps past the bound's results of [statement]'s last execution; whether the statement's own is a result set. */
    private fun ownResult(statement: Statement, first: Boolean): Boolean {
        var isResultSet = first
        repeat(bound.count) { isResultSet = statement.moreResults }
        return isResultSet
    }

    private fun Statement.rows(isResultSet: Boolean): ResultSet =
        if (isResultSet) resultSet else throw SQLException(NO_RESULT)

    private fun Statement.count(isResultSet: Boolean): Long {
        if (isResultSet) throw SQLException(A_RESULT)
        return largeUpdateCount
    }

    /** The first prepared statement, prepared with the bound: every execution carries it, and it never batches. */
    private inner class BoundPreparedStatement(
        private val target: PreparedStatement,
    ) : PreparedStatement by target {
        private fun run(): Boolean = ownResult(target, target.execute())

        override fun execute(): Boolean = run()

        override fun executeQuery(): ResultSet = target.rows(run())

        override fun executeUpdate(): Int = target.count(run()).toInt()

        override fun executeLargeUpdate(): Long = target.count(run())

        override fun addBatch(): Unit = throw IllegalStateException(NO_BATCH)

        override fun executeBatch(): IntArray = throw IllegalStateException(NO_BATCH)

        override fun executeLargeBatch(): LongArray = throw IllegalStateException(NO_BATCH)

        override fun <T : Any?> unwrap(iface: Class<T>): T =
            if (iface.isInstance(this)) iface.cast(this) else target.unwrap(iface)

        override fun isWrapperFor(iface: Class<*>): Boolean = iface.isInstance(this) || target.isWrapperFor(iface)
    }

    /**
     * The first plain statement: its first execution of one statement carries the bound; a batch, or an execution
     * with options, sends it on its own first.
     */
    private inner class BoundStatement(private val target: Statement) : Statement by target {
        private var carrying = true

        /** The SQL of the first execution, the bound in front; or the bound sent on its own first. */
        private fun carried(sql: String): String? {
            if (!carrying) return null
            carrying = false
            return bound.prefix + sql
        }

        private fun alone() {
            if (!carrying) return
            carrying = false
            target.execute(bound.alone)
        }

        override fun execute(sql: String): Boolean =
            carried(sql)?.let { ownResult(target, target.execute(it)) } ?: target.execute(sql)

        override fun executeQuery(sql: String): ResultSet =
            carried(sql)?.let { target.rows(ownResult(target, target.execute(it))) } ?: target.executeQuery(sql)

        override fun executeUpdate(sql: String): Int =
            carried(sql)?.let { target.count(ownResult(target, target.execute(it))).toInt() } ?: target.executeUpdate(sql)

        override fun executeLargeUpdate(sql: String): Long =
            carried(sql)?.let { target.count(ownResult(target, target.execute(it))) } ?: target.executeLargeUpdate(sql)

        override fun addBatch(sql: String) {
            alone()
            target.addBatch(sql)
        }

        override fun execute(sql: String, autoGeneratedKeys: Int): Boolean {
            alone()
            return target.execute(sql, autoGeneratedKeys)
        }

        override fun execute(sql: String, columnIndexes: IntArray): Boolean {
            alone()
            return target.execute(sql, columnIndexes)
        }

        override fun execute(sql: String, columnNames: Array<out String>): Boolean {
            alone()
            return target.execute(sql, columnNames)
        }

        override fun executeUpdate(sql: String, autoGeneratedKeys: Int): Int {
            alone()
            return target.executeUpdate(sql, autoGeneratedKeys)
        }

        override fun executeUpdate(sql: String, columnIndexes: IntArray): Int {
            alone()
            return target.executeUpdate(sql, columnIndexes)
        }

        override fun executeUpdate(sql: String, columnNames: Array<out String>): Int {
            alone()
            return target.executeUpdate(sql, columnNames)
        }

        override fun executeLargeUpdate(sql: String, autoGeneratedKeys: Int): Long {
            alone()
            return target.executeLargeUpdate(sql, autoGeneratedKeys)
        }

        override fun executeLargeUpdate(sql: String, columnIndexes: IntArray): Long {
            alone()
            return target.executeLargeUpdate(sql, columnIndexes)
        }

        override fun executeLargeUpdate(sql: String, columnNames: Array<out String>): Long {
            alone()
            return target.executeLargeUpdate(sql, columnNames)
        }

        override fun <T : Any?> unwrap(iface: Class<T>): T =
            if (iface.isInstance(this)) iface.cast(this) else target.unwrap(iface)

        override fun isWrapperFor(iface: Class<*>): Boolean = iface.isInstance(this) || target.isWrapperFor(iface)
    }

    private companion object {
        /** pgjdbc's own words for a query that returned no rows' result, and an update that returned one. */
        const val NO_RESULT = "No results were returned by the query."
        const val A_RESULT = "A result was returned when none was expected."

        const val NO_BATCH = "A store transaction's first statement cannot be a batch: it carries the transaction's " +
            "bound (SET LOCAL), and pgjdbc cannot batch a statement of several statements. Send a statement before it."
    }
}
