package me.ahoo.wow.api.query

import me.ahoo.wow.api.annotation.ExperimentalWowApi
import me.ahoo.wow.api.annotation.InternalWowApi

/**
 * How an ignore-case `contains`, `starts-with` or `ends-with` compares letter case, on every backend: both texts
 * after Unicode's simple case folding, character by character, with no language's own rules and nothing a store's
 * locale, collation or version decides.
 *
 * The folding is one table, `case-folding.txt` beside this class: the classes of the characters that fold together
 * (`CaseFolding.txt`'s `C` and `S` entries), generated by `scripts/case-folding.mjs` from a Unicode version it names,
 * and never edited. So `s`, `S` and `ſ` meet, as do `σ`, `Σ` and `ς` wherever they stand, `μ` and `µ`, `ǅ` and its
 * two other cases, `k` and the Kelvin sign. `İ` (U+0130) folds with no other character, so `İstanbul` does not start
 * with `is`, nor `ı` (U+0131) meet `i`.
 *
 * The in-memory reference compares [fold]ed texts. A store matches the regular expression [pattern] builds from the
 * operand, case-sensitively, so its own case functions, which follow its locale or its version, decide nothing. So
 * does a compiler of SQL outside Wow's modules that must mean what the query protocol means, as the analytics
 * catalog's dataset definitions do (#7071): [pattern] is the one entry for it; the rest is Wow's own.
 */
@ExperimentalWowApi
object CaseFolding {
    private const val RESOURCE = "/me/ahoo/wow/api/query/case-folding.txt"
    private const val HEX = 16

    /** The class of each character that folds together with others: its members, ascending. */
    private val classes: Map<Int, IntArray> by lazy {
        val stream = checkNotNull(CaseFolding::class.java.getResourceAsStream(RESOURCE)) { "$RESOURCE is missing." }
        stream.bufferedReader(Charsets.UTF_8).useLines { lines ->
            buildMap {
                lines.filter { it.isNotBlank() && !it.startsWith("#") }.forEach { line ->
                    val members = line.split(' ').map { it.toInt(HEX) }.toIntArray()
                    members.forEach { put(it, members) }
                }
            }
        }
    }

    /** The characters [codePoint] folds together with, itself among them, ascending; null when it folds with none. */
    @InternalWowApi
    fun classOf(codePoint: Int): IntArray? = classes[codePoint]

    /** [text] folded: each character as the first of its class, so two texts fold equal when their letters do. */
    @InternalWowApi
    fun fold(text: String): String {
        val folded = StringBuilder(text.length)
        text.codePoints().forEach { codePoint -> folded.appendCodePoint(classOf(codePoint)?.first() ?: codePoint) }
        return folded.toString()
    }

    /**
     * The regular expression that matches, case-sensitively, exactly the texts that fold equal to [operand]: each of
     * its characters that folds together with others as the bracket class of them all (`[Ssſ]`), any other as
     * itself, with a backslash before it when it is ASCII punctuation. No anchor: the caller adds its own.
     *
     * It reads the same in each dialect a store matches with: PostgreSQL's advanced regular expressions, MongoDB's
     * PCRE2, ClickHouse's RE2 and Lucene's regular expressions (Elasticsearch). A class holds letters only, never a
     * character a bracket expression reads as an operator, and a backslash before ASCII punctuation makes it a literal
     * in each, where RE2 refuses one before any other character.
     */
    fun pattern(operand: String): String = buildString {
        operand.codePoints().forEach { codePoint ->
            val members = classOf(codePoint)
            when {
                members != null -> {
                    append('[')
                    members.forEach(::appendCodePoint)
                    append(']')
                }
                isAsciiPunctuation(codePoint) -> append('\\').appendCodePoint(codePoint)
                else -> appendCodePoint(codePoint)
            }
        }
    }

    private fun isAsciiPunctuation(codePoint: Int): Boolean =
        codePoint in '!'.code..'/'.code || codePoint in ':'.code..'@'.code ||
            codePoint in '['.code..'`'.code || codePoint in '{'.code..'~'.code
}
