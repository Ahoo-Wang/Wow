/**
 * `node scripts/case-folding.mjs` writes the core's case folding table,
 * `api/query-api/src/main/resources/me/ahoo/wow/api/query/case-folding.txt`: Unicode's simple case folding (the `C` and
 * `S` entries of `CaseFolding.txt`) as classes of the characters that fold together, one class a line, its code
 * points in hex, ascending. An ignore-case match compares both texts after this folding, on every backend.
 *
 * The folding is read from the running Node's regular expressions: with the `u` and `i` flags, ECMAScript compares
 * two characters by exactly that folding (`Canonicalize`, "the simple or common case folding mapping" of
 * `CaseFolding.txt`), which V8 takes from its ICU. The candidates of a class are the characters sharing a full lower
 * case, a full upper case or the lower case of their upper case; every pair of candidates is then tested, so a class
 * holds only characters the folding joins, and a character joins a class only through such a test.
 *
 * The table names the Unicode version it is of (`process.versions.unicode`). Regenerate it when a newer Unicode is
 * wanted; never edit it.
 */

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'api/query-api/src/main/resources/me/ahoo/wow/api/query/case-folding.txt')

const MAX_CODE_POINT = 0x10ffff
const SURROGATES = [0xd800, 0xdfff]

const hex = (codePoint) => codePoint.toString(16).toUpperCase().padStart(4, '0')

/** Whether the folding joins [left] and [right]. */
const folds = (left, right) => new RegExp(`^\\u{${hex(left)}}$`, 'iu').test(String.fromCodePoint(right))

/** The characters sharing each key: the candidates of the classes. */
const candidates = new Map()
const add = (key, codePoint) => {
  const group = candidates.get(key)
  if (group) group.push(codePoint)
  else candidates.set(key, [codePoint])
}
for (let codePoint = 0; codePoint <= MAX_CODE_POINT; codePoint++) {
  if (codePoint >= SURROGATES[0] && codePoint <= SURROGATES[1]) continue
  const text = String.fromCodePoint(codePoint)
  const lower = text.toLowerCase()
  const upper = text.toUpperCase()
  if (lower === text && upper === text) continue
  add(`l:${lower}`, codePoint)
  add(`u:${upper}`, codePoint)
  add(`ul:${upper.toLowerCase()}`, codePoint)
}

/** Union-find over the pairs the folding joins. */
const parent = new Map()
const find = (codePoint) => {
  let at = codePoint
  while (parent.has(at) && parent.get(at) !== at) at = parent.get(at)
  return at
}
const union = (left, right) => {
  const a = find(left)
  const b = find(right)
  if (a !== b) parent.set(Math.max(a, b), Math.min(a, b))
}
for (const group of candidates.values()) {
  for (let i = 0; i < group.length; i++) {
    for (let j = i + 1; j < group.length; j++) {
      if (folds(group[i], group[j])) union(group[i], group[j])
    }
  }
}

const classes = new Map()
for (const codePoint of parent.keys()) {
  const at = find(codePoint)
  if (!classes.has(at)) classes.set(at, new Set([at]))
  classes.get(at).add(codePoint)
}
const lines = [...classes.values()]
  .map((members) => [...members].sort((a, b) => a - b))
  .filter((members) => members.length > 1)
  .sort((a, b) => a[0] - b[0])
  .map((members) => members.map(hex).join(' '))

const header = [
  `# Unicode ${process.versions.unicode} simple case folding (CaseFolding.txt, statuses C and S), as classes:`,
  '# each line the characters that fold together, in hex, ascending. Generated by scripts/case-folding.mjs',
  `# (Node ${process.version}, ICU ${process.versions.icu}); regenerate it, never edit it.`,
]
writeFileSync(target, [...header, ...lines].join('\n') + '\n')
console.log(`${lines.length} classes written to ${target}`)
