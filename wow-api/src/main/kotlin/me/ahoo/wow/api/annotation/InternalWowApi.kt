package me.ahoo.wow.api.annotation

/**
 * Marks a declaration that Wow's own modules share but that is not part of its public API: it may change or go away
 * in any release, minor or patch. Using it outside Wow requires `@OptIn(InternalWowApi::class)`.
 */
@RequiresOptIn(
    message = "Internal to Wow: it may change or be removed in any release.",
    level = RequiresOptIn.Level.ERROR,
)
@Retention(AnnotationRetention.BINARY)
@Target(
    AnnotationTarget.CLASS,
    AnnotationTarget.FUNCTION,
    AnnotationTarget.PROPERTY,
    AnnotationTarget.TYPEALIAS,
)
@MustBeDocumented
annotation class InternalWowApi
