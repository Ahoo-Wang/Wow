package me.ahoo.wow.example.shop.api.customer

import jakarta.validation.constraints.NotBlank
import me.ahoo.wow.api.annotation.CreateAggregate
import me.ahoo.wow.api.annotation.Summary

/*
 * A customer's id is in the route (`/example/customer/{id}/...`), or generated by the server when `RegisterCustomer`
 * is sent without one. A customer is also found by its user name, which it reserves (decision D50): `ChangePassword`
 * sent without an id goes to the customer holding [ChangePassword.username] (decision D182).
 */

/** Registers a customer under the user name [username], unique in the shop, with [password]. */
@CreateAggregate
@Summary("Register a customer")
data class RegisterCustomer(
    @field:NotBlank val username: String,
    @field:NotBlank val password: String,
)

/**
 * Changes the customer's password to [password]. Sent without an aggregate id, it goes to the customer whose user
 * name is [username]; sent to a customer's id, [username] is not read.
 */
@Summary("Change the password")
data class ChangePassword(
    val username: String = "",
    @field:NotBlank val password: String,
)

/** The reserved keys of the customers (decision D50). */
object CustomerKeys {
    /** The namespace of the user names a customer reserves. */
    const val USERNAME: String = "example.customer.username"
}
