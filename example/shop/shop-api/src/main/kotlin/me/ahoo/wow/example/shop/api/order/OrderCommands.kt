package me.ahoo.wow.example.shop.api.order

import me.ahoo.wow.api.annotation.CreateAggregate
import me.ahoo.wow.api.annotation.Summary
import java.math.BigDecimal

/*
 * An order's id is in the route (`/example/order/{id}/...`), or generated by the server when `CreateOrder` is sent
 * without one: no command carries an identity field (decision D68).
 */

/** Places an order for [items], at the prices the customer saw, shipped to [address]. */
@CreateAggregate
@Summary("Place an order")
data class CreateOrder(
    val items: List<Item>,
    val address: ShippingAddress,
    /** Whether the items come from the customer's cart. */
    val fromCart: Boolean = false,
) {
    data class Item(
        val productId: String,
        /** The unit price the customer saw; the order is rejected when it is no longer the product's price. */
        val price: BigDecimal,
        val quantity: Int,
    )
}

/** Ships the order to [shippingAddress] instead, while it is not paid yet. */
@Summary("Change the shipping address")
data class ChangeAddress(
    val shippingAddress: ShippingAddress,
)

/** Pays [amount] of the order with the payment [paymentId]. */
@Summary("Pay the order")
data class PayOrder(
    val paymentId: String,
    val amount: BigDecimal,
)

/** Ships a paid order. */
@Summary("Ship the order")
data object ShipOrder

/** Confirms that the customer received a shipped order. */
@Summary("Receive the order")
data object ReceiptOrder
