package me.ahoo.wow.compiler.model

import me.ahoo.wow.api.lifecycle.Lifecycle

/** Renders an [AggregateBinding] as Kotlin source that builds its model with the kernel DSL. */
internal object ModelSource {
    fun render(binding: AggregateBinding): String = buildString {
        val functionName = binding.factoryName
        val state = binding.state
        appendLine("// Generated by wow-compiler (ModelSymbolProcessor); do not edit.")
        // The admitted command is passed as the `Command<X>` its decide function was registered for.
        appendLine("@file:Suppress(\"UNCHECKED_CAST\")")
        if (binding.packageName.isNotEmpty()) {
            appendLine("package ${binding.packageName}")
        }
        appendLine()
        appendLine(
            "/** The V10 model of [${binding.root}], in bounded context [context]; [configure] runs after the bindings. */",
        )
        val parameters = listOf("context: String") + binding.dependencies.map { "${it.name}: ${it.type}" } +
            "configure: me.ahoo.wow.kernel.AggregateModelBuilder<$state>.() -> Unit = {}"
        appendLine(
            "${if (binding.internal) "internal" else "public"} fun $functionName(${parameters.joinToString(", ")}): " +
                "me.ahoo.wow.kernel.AggregateModel<$state> =",
        )
        appendLine("    me.ahoo.wow.kernel.aggregate<$state>(context, \"${binding.aggregateName}\") {")
        val ref = if (binding.stateArguments.isEmpty()) "_" else "ref"
        appendLine("        initial { $ref -> $state(${binding.stateArguments.joinToString(", ")}) }")
        binding.commands.forEach { command ->
            val dsl = when {
                command.blocking -> "decideBlocking"
                command.suspending || command.reactor -> "decideSuspending"
                else -> "decide"
            }
            val first = if (command.admitted) "this.command as $COMMAND<${command.command}>" else "command"
            val arguments = (listOf(first) + command.arguments).joinToString(", ")
            val call = "${receiver(binding)}.${command.function}($arguments)"
            val name = command.commandName?.let { ", name = \"\$type.$it\"" }.orEmpty()
            appendLine(
                "        $dsl<${command.command}>(me.ahoo.wow.kernel.Creation.${command.creation}$name) { state, command ->",
            )
            appendLine("            me.ahoo.wow.kernel.decisionOf(${awaited(call, command.reactor)})")
            appendLine("        }")
        }
        binding.mounted.forEach { mounted ->
            val name = mounted.commandName?.let { "name = \"\$type.$it\"" }.orEmpty()
            appendLine("        mount<${mounted.command}>($name)")
        }
        renderSourcing(binding.sourcing)
        renderAliasesAndUpgrades(binding)
        binding.afters.forEach { after ->
            val dsl = when {
                after.blocking -> "afterBlocking"
                after.suspending || after.reactor -> "afterSuspending"
                else -> "after"
            }
            val include = after.include.joinToString(", ", "setOf(", ")") { "$it::class.java" }
            val exclude = after.exclude.joinToString(", ", "setOf(", ")") { "$it::class.java" }
            val command = after.parameter?.let { if (after.admitted) "this.command as $it" else "command as $it" }
            val arguments = listOfNotNull(command) + after.arguments
            val call = "${receiver(binding)}.${after.function}(${arguments.joinToString(", ")})"
            appendLine("        $dsl(include = $include, exclude = $exclude) { state, command ->")
            appendLine("            me.ahoo.wow.kernel.eventsOf(${awaited(call, after.reactor)})")
            appendLine("        }")
        }
        renderOwnershipAndLifecycle(binding)
        appendLine("        configure()")
        appendLine("    }")
    }

    /**
     * The aggregate's ownership when it is not the default (decision D189), its state revision when it is not 1
     * (decision D172), the events it retired (decision D219), the state member deriving its tags (decision D220),
     * then its lifecycle commands when
     * `@AggregateRoot(lifecycle)` narrows them (decision D91).
     */
    private fun StringBuilder.renderOwnershipAndLifecycle(binding: AggregateBinding) {
        if (binding.ownership != "OWNER") {
            appendLine("        ownership(me.ahoo.wow.api.aggregate.Ownership.${binding.ownership})")
        }
        if (binding.stateRevision != 1) {
            appendLine("        stateRevision(${binding.stateRevision})")
        }
        if (binding.retiredEvents.isNotEmpty()) {
            val names = binding.retiredEvents.joinToString(", ") { "\"${former(it)}\"" }
            appendLine("        retired($names)")
        }
        binding.tags?.let { tags ->
            val read = if (tags.property) tags.member else "${tags.member}()"
            appendLine("        tags { state -> state.$read }")
        }
        if (binding.narrowsLifecycle) {
            val commands = binding.lifecycle.map { "${Lifecycle.COMMANDS.getValue(it).name}::class.java" }
            appendLine("        lifecycle(${commands.joinToString(", ")})")
        }
    }

    /** The commands' former names, then the events' upgrades (D82), each a call of its `@Upgrade` function. */
    private fun StringBuilder.renderAliasesAndUpgrades(binding: AggregateBinding) {
        binding.commands.forEach { command ->
            command.aliases.forEach { appendLine("        alias<${command.command}>(\"${former(it)}\")") }
        }
        binding.upgrades.forEach { upgrade ->
            val node = if (upgrade.objectNode) "node as $OBJECT_NODE" else "node"
            appendLine("        upgrade<${upgrade.event}>(${upgrade.from}) { node -> ${upgrade.function}($node) }")
        }
    }

    /** The evolve functions, each with its event's name and revision, then the events' former names. */
    private fun StringBuilder.renderSourcing(sourcing: List<SourcingBinding>) {
        sourcing.forEach { binding ->
            val name = binding.eventName?.let { "name = \"\$type.$it\", " }.orEmpty() +
                if (binding.revision == 1) "" else "revision = ${binding.revision}, "
            if (binding.returnsState) {
                appendLine(
                    "        evolveTo<${binding.event}>(${name}evolve = { state, event -> state.${binding.function}(event) })"
                )
            } else {
                appendLine("        evolve<${binding.event}>(${name}evolve = { event -> ${binding.function}(event) })")
            }
        }
        sourcing.forEach { binding ->
            binding.aliases.forEach { appendLine("        alias<${binding.event}>(\"${former(it)}\")") }
        }
    }

    /** A former name without a dot is within the aggregate; one with dots is a full type name. */
    private fun former(alias: String): String = if ('.' in alias) alias else "\$type.$alias"

    private fun awaited(call: String, reactor: Boolean): String =
        if (reactor) "me.ahoo.wow.reactor.awaitResult($call)" else call

    private const val COMMAND = "me.ahoo.wow.api.decide.Command"
    private const val OBJECT_NODE = "tools.jackson.databind.node.ObjectNode"

    private fun receiver(binding: AggregateBinding): String =
        if (binding.rootIsState) "state" else "${binding.root}(state)"
}
