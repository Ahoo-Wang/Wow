package me.ahoo.wow.compiler.model.source

import me.ahoo.wow.compiler.model.aggregate.Dependency
import me.ahoo.wow.compiler.model.subscription.EventParameter
import me.ahoo.wow.compiler.model.subscription.HandlerBinding
import me.ahoo.wow.compiler.model.subscription.JobBinding
import me.ahoo.wow.compiler.model.subscription.Receipt
import me.ahoo.wow.compiler.model.subscription.ReceiptBinding
import me.ahoo.wow.compiler.model.subscription.SubscriptionBinding
import me.ahoo.wow.compiler.model.symbol.blocking

/**
 * Renders the bindings of subscription processors, against the kernel's
 * `ProcessorBinding`, so a domain module depends on `wow-kernel` only:
 *
 * - per processor, in its package, `fun <processor>Handlers(dependencies): List<ProcessorBinding<*>>`: the processor
 *   constructed once with its constructor's parameters from the host's `Dependencies` (by type and `@Name`),
 * or the `object` itself, and one binding per `@OnEvent` function, each calling it directly with the typed
 *   `StateEvent<S>` and the context of its kind, its result awaited through wow-reactor when it is a Reactor
 *   publisher, and, for a saga, read as the requests of the commands it derives (`requestsOf`). A saga's
 *   `@OnRejected` handlers are bound once, as `RejectionBinding`s of the class their
 *   `CommandReceipt.Rejected<C>` names (null for `*`), and passed to each of its handlers' bindings, whose derived commands'
 *   rejections they take; so are its `@OnCommitted` handlers, as `CommittedBinding`s, which take
 *   their success receipts. A handler names the aggregates of its `@OnEvent(aggregates)`, so one of another context's
 *   reads their published streams, and says whether its state is nullable
 *   (`StateEvent<S?>`, `StateEvent<*>`), and its `@Retry` budget, merged with its processor's
 *   (`HandlerRetry`), which the runtime's per-subscription retry and timeout apply. A saga's
 *   `@OnSchedule` handler is bound with `ProcessorBinding.schedule`, its job's rule as declared;
 * - per module, the model provider's `processors` lists them all ([ModelProviderSource]).
 */
internal object SubscriptionSource {
    private const val KERNEL = "me.ahoo.wow.kernel"
    private const val PROCESSOR_BINDING = "$KERNEL.ProcessorBinding"
    private const val DEPENDENCIES = "$KERNEL.Dependencies"
    private const val STATE_EVENT = "me.ahoo.wow.api.subscribe.StateEvent"
    private const val SCHEDULE = "me.ahoo.wow.api.schedule"

    /**
     * The handlers of [binding], a processor without problems, of the bounded context [context] when the compiler knows
     * it: the context an `@OnSchedule` handler's job runs in.
     */
    fun render(binding: SubscriptionBinding, context: String? = null): String = buildString {
        val kind = KINDS.getValue(requireNotNull(binding.kind))
        val processorType = binding.processor
        appendLine("// Generated by wow-compiler (ModelSymbolProcessor); do not edit.")
        // A dependency of a generic type is found by its class and cast to the type the constructor takes.
        appendLine("@file:Suppress(\"UNCHECKED_CAST\", \"UNUSED_PARAMETER\", \"RedundantSuppression\")")
        if (binding.packageName.isNotEmpty()) {
            appendLine("package ${binding.packageName}")
        }
        appendLine()
        renderFromDependencies(binding)
        appendLine()
        appendLine("/**")
        appendLine(
            " * The subscriptions of [$processorType], constructed with the services given: one per handler, named"
        )
        appendLine(" * `${binding.name}.<function>`.")
        appendLine(" */")
        val visibility = if (binding.internal) "internal" else "public"
        val parameters = binding.dependencies.joinToString("") { "\n    ${it.name}: ${it.type}," }
        // A processor without problems has a handler at least: one that declares none is refused.
        val handlers = binding.handlers
        appendLine("$visibility fun ${binding.factoryName}($parameters\n): List<$PROCESSOR_BINDING<*>> {")
        val instance = if (binding.isObject) {
            processorType
        } else {
            "$processorType(${binding.dependencies.joinToString(", ") { it.name }})"
        }
        appendLine("    val processor = $instance")
        val rejections = kind == SAGA && binding.rejections.isNotEmpty()
        if (rejections) {
            appendLine("    val rejections = listOf<${Receipt.REJECTED.binding}<*>>(")
            binding.rejections.forEach { renderReceipt(binding, it) }
            appendLine("    )")
        }
        val commits = kind == SAGA && binding.commits.isNotEmpty()
        if (commits) {
            appendLine("    val commits = listOf<${Receipt.COMMITTED.binding}<*>>(")
            binding.commits.forEach { renderReceipt(binding, it) }
            appendLine("    )")
        }
        appendLine("    return listOf(")
        handlers.forEach { handler -> renderHandler(binding, handler, kind, rejections, commits, context) }
        appendLine("    )")
        appendLine("}")
    }

    /**
     * The subscriptions of [binding]'s processor constructed with the services the host's `Dependencies` gives, by type
     * and `@Name`: the model provider's, and a host's.
     */
    private fun StringBuilder.renderFromDependencies(binding: SubscriptionBinding) {
        appendLine("/**")
        appendLine(
            " * The subscriptions of [${binding.processor}], constructed with the services [dependencies] gives: one"
        )
        appendLine(" * per handler, named `${binding.name}.<function>`.")
        appendLine(" */")
        appendLine("public fun ${binding.factoryName}(")
        appendLine("    dependencies: $DEPENDENCIES,")
        val building = binding.simpleNames.joinToString(".")
        val arguments = binding.dependencies.joinToString("") { "\n    ${lookup(it, building)}," }
        appendLine(
            "): List<$PROCESSOR_BINDING<*>> = ${binding.factoryName}($arguments${if (arguments.isEmpty()) "" else "\n"})"
        )
    }

    @Suppress("LongParameterList")
    private fun StringBuilder.renderHandler(
        binding: SubscriptionBinding,
        handler: HandlerBinding,
        kind: String,
        rejections: Boolean,
        commits: Boolean,
        context: String?,
    ) {
        val job = handler.job
        if (job != null) {
            renderJob(binding, handler, job, rejections, commits, context)
            return
        }
        // A star projection's state is nullable by default; a named state says so only when it is.
        val nullable = handler.state != null && handler.nullableState
        val state = handler.state?.let { if (nullable) "$it?" else it } ?: "Any"
        val stateType = handler.state?.let { "$it::class.java" } ?: "null"
        val body = handler.event?.let { eventBody(handler, it, kind) } ?: streamBody(handler, kind)
        val contextParameter = if (handler.context || handler.event != null) "context" else "_"
        val rejectionArgument = (if (rejections) ", rejections = rejections" else "") +
            if (commits) ", commits = commits" else ""
        val optionalArguments = optionalArguments(handler, nullable)
        appendLine(
            "        $PROCESSOR_BINDING.$kind<$state>(\"${escape(binding.name)}\", \"${handler.function}\", " +
                "$stateType, ${handler.blocking}$rejectionArgument$optionalArguments) {",
        )
        appendLine("                event: $STATE_EVENT<$state>, $contextParameter ->")
        appendLine("            $body")
        appendLine("        },")
    }

    /** The body of a handler of the whole stream: its call, a saga's read as the requests of the commands it derives. */
    private fun streamBody(handler: HandlerBinding, kind: String): String {
        val arguments = if (handler.context) "event, context" else "event"
        val call = "processor.${handler.callee}($arguments)"
        val awaited = if (handler.reactor) "me.ahoo.wow.reactor.awaitResult($call)" else call
        return if (kind == SAGA) "$KERNEL.requestsOf($awaited)" else awaited
    }

    /**
     * The body of a handler of each event of a type: `eachEvent` calls the function once per such
     * event of the stream, with its `StateTypedEvent` or the event itself, and the context of that call; a saga's
     * calls' commands are the stream's, in order.
     */
    private fun eventBody(handler: HandlerBinding, event: EventParameter, kind: String): String {
        val argument = if (event.form == EventParameter.TYPED) "typed" else "typed.event"
        val arguments = if (handler.context) "$argument, invocation" else argument
        val call = "processor.${handler.callee}($arguments)"
        val awaited = if (handler.reactor) "me.ahoo.wow.reactor.awaitResult($call)" else call
        val result = if (kind == SAGA) "$KERNEL.requestsOf($awaited)" else awaited
        val invocation = if (handler.context) "invocation" else "_"
        val each = "$KERNEL.eachEvent(event, ${event.source}::class.java, context) { typed, $invocation -> $result }"
        return if (kind == SAGA) "$each.flatten()" else each
    }

    /**
     * The arguments of [handler]'s binding that it gives only when it has them: the aggregates of its
     * `@OnEvent(aggregates)`, whether its state is [nullable], its `@Retry` budget, and the start its `@OnEvent(start)`
     * declares (the runtime gives one that declares none its kind's and source's), and the classes of
     * its `@OnEvent(calls)`, the only ones its `SagaContext.call` takes.
     */
    private fun optionalArguments(handler: HandlerBinding, nullable: Boolean): String = buildString {
        if (handler.aggregates.isNotEmpty()) {
            append(", aggregates = listOf(${handler.aggregates.joinToString(", ") { "\"${escape(it)}\"" }})")
        }
        if (nullable) {
            append(", nullableState = true")
        }
        handler.retry?.let { append(", retry = ${it.source()}") }
        handler.start?.let { append(", startFrom = $KERNEL.StartFrom.$it") }
        handler.event?.let { append(", eventType = ${it.source}::class.java") }
        if (handler.callSources.isNotEmpty()) {
            append(", calls = listOf(${handler.callSources.joinToString(", ") { "$it::class.java" }})")
        }
    }

    /**
     * A saga's `@OnSchedule` handler: `ProcessorBinding.schedule` of its [job] in the bounded [context] when known, whose
     * handle calls the function with the tick and, if it takes it, the saga's context.
     */
    @Suppress("LongParameterList")
    private fun StringBuilder.renderJob(
        binding: SubscriptionBinding,
        handler: HandlerBinding,
        job: JobBinding,
        rejections: Boolean,
        commits: Boolean,
        context: String?,
    ) {
        val arguments = if (handler.context) "tick, context" else "tick"
        val call = "processor.${handler.callee}($arguments)"
        val awaited = if (handler.reactor) "me.ahoo.wow.reactor.awaitResult($call)" else call
        val rule = "$SCHEDULE.ScheduleRule.Cron.of(\"${escape(job.cron)}\", \"${escape(job.zone)}\", " +
            "$SCHEDULE.Misfire.${job.misfire})"
        val definition = "$KERNEL.schedule.ScheduleJob.of(\"${escape(job.name)}\", $rule, " +
            "$SCHEDULE.JobScope.${job.scope}, ${job.sharded})"
        val receipts = (if (rejections) ", rejections = rejections" else "") +
            if (commits) ", commits = commits" else ""
        val retry = handler.retry?.let { ", retry = ${it.source()}" }.orEmpty()
        val bounded = context?.let { ", context = \"${escape(it)}\"" }.orEmpty()
        appendLine(
            "        $PROCESSOR_BINDING.schedule(\"${escape(binding.name)}\", \"${handler.function}\", $definition, " +
                "${handler.blocking}$receipts$retry$bounded) {",
        )
        appendLine("                tick: $SCHEDULE.ScheduleTick, ${if (handler.context) "context" else "_"} ->")
        appendLine("            $KERNEL.requestsOf($awaited)")
        appendLine("        },")
    }

    /**
     * A receipt handler of the saga [binding], `@OnRejected` or `@OnCommitted`: its call, read as the commands it
     * derives.
     */
    private fun StringBuilder.renderReceipt(binding: SubscriptionBinding, handler: ReceiptBinding) {
        val command = handler.commandSource ?: "Any"
        val commandType = handler.commandSource?.let { "$it::class.java" } ?: "null"
        val parameter = if (handler.receipt == Receipt.REJECTED) "rejected" else "committed"
        val arguments = if (handler.context) "$parameter, context" else parameter
        val call = "processor.${handler.callee}($arguments)"
        val awaited = if (handler.reactor) "me.ahoo.wow.reactor.awaitResult($call)" else call
        appendLine(
            "        ${handler.receipt.binding}.of<$command>(\"${escape(binding.name)}\", \"${handler.function}\", " +
                "$commandType, ${handler.blocking}) {",
        )
        appendLine(
            "                $parameter: ${handler.receipt.parameter}<$command>, ${if (handler.context) "context" else "_"} ->",
        )
        appendLine("            $KERNEL.requestsOf($awaited)")
        appendLine("        },")
    }

    /**
     * The model provider's `processors`: the bindings of every processor of [bindings], in the
     * provider's class body.
     */
    fun renderProcessors(bindings: List<SubscriptionBinding>): String = buildString {
        appendLine("    override fun processors(")
        appendLine("        dependencies: $DEPENDENCIES,")
        appendLine("    ): List<$PROCESSOR_BINDING<*>> = listOf(")
        bindings.sortedBy { it.processor }.forEach { binding ->
            val factory = if (binding.packageName.isEmpty()) {
                binding.factoryName
            } else {
                "${binding.packageName}.${binding.factoryName}"
            }
            appendLine("        $factory(dependencies),")
        }
        appendLine("    ).flatten()")
    }

    /**
     * The lookup of [dependency] in the `dependencies` of a generated function that builds [building] with it: by its
     * class and qualifier; a parameterized one by its full type too, naming the parameter, and cast to its type.
     */
    fun lookup(dependency: Dependency, building: String): String {
        val qualifier = dependency.qualifier?.let { "\"${escape(it)}\"" } ?: "null"
        val raw = "${dependency.erasure}::class.javaObjectType"
        val lookup = when (val fullType = dependency.fullType) {
            null -> "dependencies.get($raw, $qualifier, \"${escape(building)}\")"
            else -> "dependencies.get($raw, $fullType, $qualifier, \"${escape(building)}\", " +
                "\"${escape(dependency.name)}\")"
        }
        return if (dependency.erasure == dependency.type) lookup else "$lookup as ${dependency.type}"
    }

    private const val SAGA = "saga"
    private val KINDS = mapOf("PROJECT" to "project", "REACT" to "react", "SAGA" to SAGA)

    private fun escape(text: String): String = text.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
}
