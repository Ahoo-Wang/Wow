package me.ahoo.wow.compiler.model.source

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.symbol.KSClassDeclaration
import me.ahoo.wow.compiler.model.aggregate.AccessBinding

/**
 * The access attributes of an aggregate's state: `<State>Access`, an object extending `wow-api`'s `AccessAttributes`
 * (the built-in `OWNER` and `SPACE`) with a typed reference to each attribute the state declares (`@Access`), what
 * the service's access policies name and the generated model declares. Each constant is the attribute's name in upper
 * snake case, as a query field's segment is named: `sharedWith` is `SHARED_WITH`. Generated for a state that declares
 * an attribute; internal when the state or the class of an attribute's values is.
 */
internal object AccessSource {
    private const val ATTRIBUTE = "me.ahoo.wow.api.access.AccessAttribute"
    private const val ATTRIBUTES = "me.ahoo.wow.api.access.AccessAttributes"

    /** The name of the object generated for [state]: its simple names joined, then `Access`. */
    fun className(state: KSClassDeclaration): String =
        state.qualifiedName!!.asString().removePrefix("${state.packageName.asString()}.").replace(".", "") + "Access"

    /** The qualified name of the object generated for [state]. */
    fun qualifiedName(state: KSClassDeclaration): String =
        state.packageName.asString().let { if (it.isEmpty()) className(state) else "$it.${className(state)}" }

    /** Writes [state]'s `<State>Access` of [attributes], unless [generated], the states already written, holds it. */
    fun generate(
        codeGenerator: CodeGenerator,
        state: KSClassDeclaration,
        attributes: List<AccessBinding>,
        internal: Boolean,
        generated: MutableSet<String>,
    ) {
        if (attributes.isEmpty() || !generated.add(state.qualifiedName!!.asString())) {
            return
        }
        codeGenerator.createNewFile(
            Dependencies(aggregating = false, sources = listOfNotNull(state.containingFile).toTypedArray()),
            state.packageName.asString(),
            className(state),
        ).bufferedWriter().use { it.write(render(state, attributes, internal)) }
    }

    fun render(state: KSClassDeclaration, attributes: List<AccessBinding>, internal: Boolean): String = buildString {
        val packageName = state.packageName.asString()
        val visibility = if (internal || attributes.any { it.internalValue }) "internal" else "public"
        appendLine("// Generated by wow-compiler (ModelSymbolProcessor); do not edit.")
        if (packageName.isNotEmpty()) {
            appendLine("package $packageName")
        }
        appendLine()
        appendLine("/**")
        appendLine(" * The access attributes of [${state.qualifiedName!!.asString()}]: the built-in ones of")
        appendLine(" * [$ATTRIBUTES] and the state's own (`@Access`).")
        appendLine(" */")
        val stateType = state.qualifiedName!!.asString()
        appendLine("$visibility object ${className(state)} : $ATTRIBUTES<$stateType>() {")
        attributes.forEachIndexed { index, attribute ->
            if (index > 0) {
                appendLine()
            }
            val (kind, factory) = if (attribute.multiple) "Multiple" to "multiple" else "Single" to "single"
            appendLine("    /** `${attribute.name}` */")
            appendLine("    @kotlin.jvm.JvmField")
            appendLine(
                "    $visibility val ${attribute.constant}: $ATTRIBUTE.$kind<$stateType, ${attribute.valueType}> = " +
                    "$ATTRIBUTE.$factory(\"${attribute.name}\", ${attribute.valueType}::class.javaObjectType)",
            )
        }
        appendLine("}")
    }
}
