package me.ahoo.wow.compiler.model

/**
 * Renders the bindings of subscription processors (design 04 §1, decision D37), against the runtime's
 * `me.ahoo.wow.runtime.binding` package:
 *
 * - per processor, in its package, `fun <processor>Handlers(dependencies): List<BoundHandler<*>>`: the processor
 *   constructed once with its constructor's parameters from the host's `Dependencies` (by type and `@Name`, decision
 *   D119), or the `object` itself, and one handler per `@OnEvent` function, each calling it directly with the typed
 *   `StateEvent<S>` and the context of its kind, its result awaited through wow-reactor when it is a Reactor
 *   publisher (decision D49), and, for a saga, read as the commands it derives (`derivedOf`);
 * - per module, beside the model provider, the `SubscriptionProvider` that lists them all.
 */
internal object SubscriptionSource {
    const val SUBSCRIPTION_PROVIDER = "me.ahoo.wow.runtime.binding.SubscriptionProvider"
    private const val BINDING = "me.ahoo.wow.runtime.binding"
    private const val DEPENDENCIES = "me.ahoo.wow.kernel.Dependencies"
    private const val STATE_EVENT = "me.ahoo.wow.api.subscribe.StateEvent"

    /** `shop-domain` gives `ShopDomainSubscriptionProvider`. */
    fun className(module: String): String =
        ModelProviderSource.className(module).removeSuffix("ModelProvider") + "SubscriptionProvider"

    /** The handlers of [binding], a processor without problems. */
    fun render(binding: SubscriptionBinding): String = buildString {
        val kind = KINDS.getValue(requireNotNull(binding.kind))
        val processorType = binding.processor
        appendLine("// Generated by wow-compiler (ModelSymbolProcessor); do not edit.")
        // A dependency of a generic type is found by its class and cast to the type the constructor takes.
        appendLine("@file:Suppress(\"UNCHECKED_CAST\", \"UNUSED_PARAMETER\", \"RedundantSuppression\")")
        if (binding.packageName.isNotEmpty()) {
            appendLine("package ${binding.packageName}")
        }
        appendLine()
        appendLine("/** The subscriptions of [$processorType]: one per handler, named `${binding.name}.<function>`. */")
        appendLine("public fun ${binding.factoryName}(")
        appendLine("    dependencies: $DEPENDENCIES,")
        appendLine("): List<$BINDING.BoundHandler<*>> {")
        val instance = if (binding.isObject) {
            processorType
        } else {
            "$processorType(${binding.dependencies.joinToString(", ") { dependency(it) }})"
        }
        appendLine("    val processor = $instance")
        appendLine("    return listOf(")
        binding.handlers.forEach { handler -> renderHandler(binding, handler, kind) }
        appendLine("    )")
        appendLine("}")
    }

    private fun StringBuilder.renderHandler(binding: SubscriptionBinding, handler: HandlerBinding, kind: String) {
        val state = handler.state ?: "Any"
        val stateType = handler.state?.let { "$it::class.java" } ?: "null"
        val arguments = if (handler.context) "event, context" else "event"
        val call = "processor.${handler.function}($arguments)"
        val awaited = if (handler.reactor) "me.ahoo.wow.reactor.awaitResult($call)" else call
        val body = if (kind == SAGA) "$BINDING.derivedOf($awaited)" else awaited
        appendLine(
            "        $BINDING.BoundHandler.$kind<$state>(\"${escape(binding.name)}\", \"${handler.function}\", " +
                "$stateType, ${handler.blocking}) {",
        )
        appendLine("                event: $STATE_EVENT<$state>, ${if (handler.context) "context" else "_"} ->")
        appendLine("            $body")
        appendLine("        },")
    }

    /** The module's subscription provider: the handlers of every processor of [bindings]. */
    fun renderProvider(
        packageName: String,
        className: String,
        context: String,
        bindings: List<SubscriptionBinding>,
    ): String = buildString {
        appendLine("// Generated by wow-compiler (ModelSymbolProcessor); do not edit.")
        if (packageName.isNotEmpty()) {
            appendLine("package $packageName")
        }
        appendLine()
        appendLine("/** The subscription binding index of the module (decisions D37, D107). */")
        appendLine("public class $className : $SUBSCRIPTION_PROVIDER {")
        appendLine("    override val context: String = \"${escape(context)}\"")
        appendLine()
        appendLine("    override fun handlers(")
        appendLine("        dependencies: $DEPENDENCIES,")
        appendLine("    ): List<$BINDING.BoundHandler<*>> = listOf(")
        bindings.sortedBy { it.processor }.forEach { binding ->
            val factory = if (binding.packageName.isEmpty()) {
                binding.factoryName
            } else {
                "${binding.packageName}.${binding.factoryName}"
            }
            appendLine("        $factory(dependencies),")
        }
        appendLine("    ).flatten()")
        appendLine("}")
    }

    private fun dependency(dependency: Dependency): String {
        val qualifier = dependency.qualifier?.let { ", \"${escape(it)}\"" }.orEmpty()
        val lookup = "dependencies.get(${dependency.erasure}::class.javaObjectType$qualifier)"
        return if (dependency.erasure == dependency.type) lookup else "$lookup as ${dependency.type}"
    }

    private const val SAGA = "saga"
    private val KINDS = mapOf("PROJECT" to "project", "REACT" to "react", "SAGA" to SAGA)

    private fun escape(text: String): String = text.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
}
