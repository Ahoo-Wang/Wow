package me.ahoo.wow.compiler.model.source

import me.ahoo.wow.compiler.model.aggregate.AggregateBinding
import me.ahoo.wow.compiler.model.aggregate.Dependency
import me.ahoo.wow.compiler.model.route.ServiceRouteBinding
import me.ahoo.wow.compiler.model.subscription.SubscriptionBinding

/**
 * Renders the binding index of a module: a `me.ahoo.wow.kernel.ModelProvider` that builds each
 * aggregate model with its generated factory, every dependency of the factory taken from the host's `Dependencies`
 * by its type, lists the handlers of its subscription processors (`processors`, [SubscriptionSource]) and of its
 * service routes (`routes`, [ServiceRouteSource]),
 * and names the module's Manifest fragment.
 *
 * The class lives in the deepest package the module's models and subscriptions share, named after the module
 * ([className]): two modules of a service differ in their fragments, so in their names too.
 */
internal object ModelProviderSource {
    const val MODEL_PROVIDER = "me.ahoo.wow.kernel.ModelProvider"

    /**
     * The binding this compiler generates against (`ModelProvider.BINDING` of the kernel it is released with): the
     * kernel refuses at startup a module generated for another, instead of failing on its first command. The
     * compiler's tests hold it equal to the kernel's.
     */
    const val BINDING: Int = 3

    /** `shop-domain` gives `ShopDomainModelProvider`. */
    fun className(module: String): String {
        val words = module.split(Regex("[^A-Za-z0-9]+")).filter { it.isNotEmpty() }
        val name = words.joinToString("") { word -> word.replaceFirstChar { it.uppercase() } }
        return (if (name.firstOrNull()?.isLetter() == true) name else "Module$name") + "ModelProvider"
    }

    /** The deepest package all of [packages] are in, the root package when they share none. */
    fun commonPackage(packages: Collection<String>): String {
        val split = packages.map { if (it.isEmpty()) emptyList() else it.split('.') }
        val first = split.firstOrNull() ?: return ""
        val common = first.indices.takeWhile { index -> split.all { it.getOrNull(index) == first[index] } }
        return first.take(common.size).joinToString(".")
    }

    fun render(
        packageName: String,
        className: String,
        context: String,
        fragment: String,
        aggregates: List<AggregateBinding>,
        processors: List<SubscriptionBinding> = emptyList(),
        routes: List<ServiceRouteBinding> = emptyList(),
    ): String = buildString {
        appendLine("// Generated by wow-compiler (ModelSymbolProcessor); do not edit.")
        // A dependency of a generic type is found by its class and cast to the type the factory takes.
        appendLine("@file:Suppress(\"UNCHECKED_CAST\")")
        if (packageName.isNotEmpty()) {
            appendLine("package $packageName")
        }
        appendLine()
        appendLine("/** The binding index of the module of Manifest fragment [fragment]. */")
        appendLine("public class $className : $MODEL_PROVIDER {")
        appendLine("    override val binding: Int = $BINDING")
        appendLine()
        appendLine("    override val context: String = \"${escape(context)}\"")
        appendLine()
        appendLine("    override val fragment: String = \"${escape(fragment)}\"")
        appendLine()
        appendLine("    override fun models(")
        appendLine("        dependencies: me.ahoo.wow.kernel.Dependencies,")
        appendLine("    ): List<me.ahoo.wow.kernel.AggregateModel<*>> = listOf(")
        aggregates.sortedBy { it.root }.forEach { aggregate ->
            val factory = if (aggregate.packageName.isEmpty()) {
                aggregate.factoryName
            } else {
                "${aggregate.packageName}.${aggregate.factoryName}"
            }
            val building = "the ${aggregate.rootSimpleName} model"
            val arguments = listOf("context") + aggregate.dependencies.map { dependency(it, building) }
            appendLine("        $factory(${arguments.joinToString(", ")}),")
        }
        appendLine("    )")
        if (processors.isNotEmpty()) {
            appendLine()
            append(SubscriptionSource.renderProcessors(processors))
        }
        if (routes.isNotEmpty()) {
            appendLine()
            append(ServiceRouteSource.render(context, routes))
        }
        appendLine("}")
    }

    private fun dependency(dependency: Dependency, building: String): String =
        SubscriptionSource.lookup(dependency, building)

    private fun escape(text: String): String = text.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
}
