package me.ahoo.wow.manifest.tools

import me.ahoo.test.asserts.assert
import me.ahoo.wow.api.annotation.Description
import me.ahoo.wow.manifest.AggregateManifest
import me.ahoo.wow.manifest.CommandManifest
import me.ahoo.wow.manifest.ContextManifest
import me.ahoo.wow.manifest.EventManifest
import me.ahoo.wow.manifest.Manifest
import me.ahoo.wow.manifest.PublishedManifest
import me.ahoo.wow.manifest.StateManifest
import me.ahoo.wow.manifest.copyWith
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import java.math.BigDecimal
import java.time.Instant
import java.time.OffsetDateTime

class StateViewSourcesTest {
    enum class Status { OPEN, CLOSED }

    /** A class of the api: the view references it. */
    data class Item(val sku: String, val quantity: Int)

    /** A class of the domain: the view copies it. */
    @Description("Where the cart goes.")
    data class Address(val city: String, val zip: String?)

    data class Node(val name: String, val children: List<Node> = emptyList())

    class CartState(val id: String) {
        var status: Status = Status.OPEN
        var items: List<Item> = emptyList()
        var codes: Set<String> = emptySet()
        var address: Address? = null
        var tree: Node? = null
        var amount: BigDecimal = BigDecimal.ZERO
        var placedAt: Instant? = null
        var offsetAt: OffsetDateTime? = null
        var counts: Map<String, Long> = emptyMap()
        var small: Short = 0
        var parent: CartState? = null
    }

    private val api = setOf(Item::class.java.name)

    /** The context `shop` of [aggregates] of [state], its schemas introspected as the plugin does. */
    private fun contract(
        state: Class<*>,
        vararg aggregates: String,
        published: List<PublishedManifest> = emptyList()
    ): Manifest {
        val context = ContextManifest(
            "shop",
            aggregates = aggregates.map { name ->
                AggregateManifest(
                    name = name,
                    state = StateManifest(Manifest.schemaRef(state.name)),
                    commands = listOf(CommandManifest("Add", schema = Manifest.schemaRef("shop.api.cart.Add"))),
                    events = listOf(EventManifest("Added", schema = Manifest.schemaRef("shop.api.cart.Added"))),
                )
            },
            published = published,
        )
        val fragment = Manifest(contexts = listOf(context))
            .copyWith(
                defs = mapOf(
                    "shop.api.cart.Add" to mapOf("type" to "object"),
                    "shop.api.cart.Added" to mapOf("type" to "object")
                )
            )
        return SchemaIntrospector(javaClass.classLoader).complete(fragment)
    }

    private fun views(
        contract: Manifest,
        onClassPath: (String) -> Boolean = { it in api || it.startsWith("java.") },
    ): List<ContractSources.Source> =
        StateViewSources(contract.defs, onClassPath).of(contract.contexts.single())

    @Test
    fun `a view should hold the state's fields, referencing the api's classes and copying the domain's`() {
        val view = views(contract(CartState::class.java, "cart")).single()
        view.path.assert().isEqualTo("shop/api/cart/CartStateView.kt")
        view.text.assert().isEqualTo(
            """
            // Generated by the Wow Gradle plugin from this api module's contract; do not edit.
            package shop.api.cart

            import me.ahoo.wow.api.read.StateView

            /**
             * The state of `shop.cart` as another context reads it, from its contract.
             */
            @StateView("shop.cart")
            public data class CartStateView(
                /** Where the cart goes. */
                val address: CartStateView.Address? = null,
                val amount: java.math.BigDecimal,
                val codes: Set<String>,
                val counts: Map<String, Long>,
                val id: String,
                val items: List<me.ahoo.wow.manifest.tools.StateViewSourcesTest.Item>,
                val offsetAt: java.time.OffsetDateTime? = null,
                val parent: CartStateView? = null,
                val placedAt: java.time.Instant? = null,
                val small: Short,
                val status: CartStateView.Status,
                val tree: CartStateView.Node? = null,
            ) {
                /** `me.ahoo.wow.manifest.tools.StateViewSourcesTest${'$'}Address`, as the view copies it. */
                public data class Address(
                    val city: String,
                    val zip: String? = null,
                )

                /** `me.ahoo.wow.manifest.tools.StateViewSourcesTest${'$'}Status`, as the view copies it. */
                public enum class Status {
                    OPEN,
                    CLOSED,
                }

                /** `me.ahoo.wow.manifest.tools.StateViewSourcesTest${'$'}Node`, as the view copies it. */
                public data class Node(
                    val children: List<CartStateView.Node>? = null,
                    val name: String,
                )
            }

            """.trimIndent(),
        )
    }

    @Test
    fun `an enumeration on the api's class path should be referenced`() {
        val text = views(
            contract(CartState::class.java, "cart")
        ) { it.startsWith("java.") || it != CartState::class.java.name }
            .single().text
        text.assert().contains("val status: me.ahoo.wow.manifest.tools.StateViewSourcesTest.Status,")
            .doesNotContain("enum class")
    }

    @Test
    fun `a state shared by two aggregates should fail, a view being of one aggregate`() {
        assertThrows<IllegalStateException> { views(contract(CartState::class.java, "cart", "wishlist")) }
            .message.assert().contains("shop.cart, shop.wishlist share the state ${CartState::class.java.name}")
    }

    @Test
    fun `a state the contract withholds should have no view`() {
        val published = listOf(PublishedManifest("cart", "shop.cart", includeState = false))
        views(contract(CartState::class.java, "cart", published = published)).assert().isEmpty()
        val opaque = contract(CartState::class.java, "cart").let {
            it.copyWith(defs = it.defs + (CartState::class.java.name to mapOf("type" to "object")))
        }
        views(opaque).assert().isEmpty()
    }

    /** The view of a state whose one field [field] has the schema [schema], with [defs]. */
    private fun viewOf(
        schema: Map<String, Any?>,
        defs: Map<String, Any?> = emptyMap(),
        required: Boolean = true
    ): String {
        val state = mapOf(
            "type" to "object",
            "properties" to mapOf("field" to schema),
            "required" to if (required) listOf("field") else emptyList(),
        )
        val contract = contract(CartState::class.java, "cart").let {
            it.copyWith(defs = it.defs + defs + (CartState::class.java.name to state))
        }
        return views(contract).single().text
    }

    private fun fieldOf(schema: Map<String, Any?>, defs: Map<String, Any?> = emptyMap(), required: Boolean = true): String =
        viewOf(schema, defs, required).lines().single { it.trim().startsWith("val field") }.trim()

    @Test
    fun `each format should read as its type`() {
        mapOf(
            mapOf("type" to "integer", "format" to "int32") to "Int",
            mapOf("type" to "integer", "format" to "int64") to "Long",
            mapOf("type" to "integer", "format" to "bigint") to "java.math.BigInteger",
            mapOf("type" to "number") to "Double",
            mapOf("type" to "number", "format" to "float") to "Float",
            mapOf("type" to "number", "format" to "decimal") to "java.math.BigDecimal",
            mapOf("type" to "string") to "String",
            mapOf("type" to "string", "format" to "email") to "String",
            mapOf("type" to "string", "format" to "date-time") to "java.time.Instant",
            mapOf("type" to "string", "format" to "date") to "java.time.LocalDate",
            mapOf("type" to "string", "format" to "time") to "java.time.OffsetTime",
            mapOf("type" to "string", "format" to "duration") to "java.time.Duration",
            mapOf("type" to "string", "format" to "uuid") to "java.util.UUID",
            mapOf("type" to "string", "format" to "uri") to "java.net.URI",
            mapOf("type" to "string", "format" to "date-time", "x-wow-class" to "java.time.ZonedDateTime") to
                "java.time.ZonedDateTime",
            mapOf("type" to "string", "x-wow-class" to "java.lang.Character") to "Char",
            mapOf("type" to "boolean") to "Boolean",
            mapOf("type" to "array", "items" to mapOf("type" to "string")) to "List<String>",
            mapOf("type" to "array", "items" to mapOf("type" to "string"), "uniqueItems" to true) to "Set<String>",
            mapOf("type" to "array", "items" to mapOf("type" to listOf("string", "null"))) to "List<String?>",
            mapOf("type" to "object", "additionalProperties" to mapOf("type" to "boolean")) to "Map<String, Boolean>",
            emptyMap<String, Any?>() to "tools.jackson.databind.JsonNode",
            mapOf("type" to "object") to "tools.jackson.databind.node.ObjectNode",
            mapOf("type" to "object", "additionalProperties" to true) to "tools.jackson.databind.node.ObjectNode",
            mapOf("type" to "object", "additionalProperties" to emptyMap<String, Any?>()) to
                "tools.jackson.databind.node.ObjectNode",
            mapOf("type" to "object", "additionalProperties" to mapOf("type" to "integer", "format" to "int32")) to
                "Map<String, Int>",
            mapOf("type" to "array", "items" to emptyMap<String, Any?>()) to "List<tools.jackson.databind.JsonNode>",
        ).forEach { (schema, type) ->
            fieldOf(schema).assert().describedAs(schema.toString()).isEqualTo("val field: $type,")
        }
    }

    class ReadingsState(val id: String) {
        var nullableItems: List<Long?> = emptyList()
        var nullableValues: Map<String, String?> = emptyMap()
        var values: Map<String, Long> = emptyMap()
        var itemsOrNull: List<Long>? = null
        var addresses: List<Map<String, Address?>> = emptyList()
    }

    @Test
    fun `an element or a value should be nullable in the view where its Kotlin type argument is`() {
        val text = views(contract(ReadingsState::class.java, "readings")).single().text
        text.assert().contains(
            "val addresses: List<Map<String, ReadingsStateView.Address?>>,",
            "val itemsOrNull: List<Long>? = null,",
            "val nullableItems: List<Long?>,",
            "val nullableValues: Map<String, String?>,",
            "val values: Map<String, Long>,",
        )
    }

    @Test
    fun `a nullable or optional field should be nullable, null by default`() {
        fieldOf(emptyMap(), required = false).assert().isEqualTo("val field: tools.jackson.databind.JsonNode? = null,")
        fieldOf(mapOf("type" to listOf("string", "null"))).assert().isEqualTo("val field: String? = null,")
        fieldOf(mapOf("type" to "string"), required = false).assert().isEqualTo("val field: String? = null,")
        fieldOf(
            mapOf("anyOf" to listOf(mapOf("type" to "null"), mapOf("\$ref" to "#/\$defs/T"))),
            defs = mapOf("T" to mapOf("type" to "integer", "format" to "int64")),
        ).assert().isEqualTo("val field: Long? = null,")
    }

    @Test
    fun `a field whose name is no plain Kotlin name should be quoted`() {
        val state = mapOf(
            "type" to "object",
            "properties" to mapOf("first-name" to mapOf("type" to "string"), "in" to mapOf("type" to "string")),
            "required" to listOf("first-name", "in"),
        )
        val contract = contract(CartState::class.java, "cart").let {
            it.copyWith(defs = it.defs + (CartState::class.java.name to state))
        }
        views(contract).single().text.assert().contains("val `first-name`: String,", "val `in`: String,")
    }

    @Test
    fun `a type the schema does not determine should fail the generation, naming the field`() {
        fun failure(schema: Map<String, Any?>, defs: Map<String, Any?> = emptyMap()): String =
            assertThrows<IllegalStateException> { viewOf(schema, defs) }.message!!
        val field = "${CartState::class.java.name}.field"
        failure(mapOf("type" to "integer")).assert().contains(field, "an integer of no format")
        failure(mapOf("type" to "integer", "format" to "int128")).assert().contains("the format int128")
        failure(mapOf("type" to "object", "properties" to mapOf("a" to mapOf("type" to "string"))))
            .assert().contains(field, "an object of no class")
        failure(mapOf("type" to "object", "additionalProperties" to false)).assert().contains("accepts no property")
        failure(mapOf("anyOf" to listOf(mapOf("type" to "string"), mapOf("type" to "boolean"))))
            .assert().contains("one of several types")
        failure(mapOf("type" to "object", "x-wow-class" to "shop.domain.Page(shop.domain.Item)"))
            .assert().contains("the parameterized class shop.domain.Page(shop.domain.Item)")
        failure(mapOf("type" to "object", "x-wow-class" to "shop.domain.Shape"))
            .assert().contains("shop.domain.Shape, which is not on the api's class path and has no fields")
        failure(mapOf("type" to "string", "enum" to listOf("in-stock"), "x-wow-class" to "shop.domain.Stock"))
            .assert().contains("the enumeration shop.domain.Stock has the value in-stock, which is no Kotlin name")
        failure(
            mapOf("\$ref" to "#/\$defs/Missing")
        ).assert().contains("refers to #/\$defs/Missing, which is not defined")
        failure(mapOf("type" to "null")).assert().contains("its type is null")
        failure(mapOf("type" to "string", "x-wow-class" to "shop.domain.CartStateView"))
            .assert().contains("whose simple name another copied class of the view has")
    }

    @Test
    fun `two states viewed under one name should fail`() {
        val contract = contract(CartState::class.java, "cart")
        val context = contract.contexts.single()
        val cart = context.aggregates.single()
        // Another state class of the same simple name, in the same package.
        val other = cart.copyWith(name = "other", state = StateManifest(Manifest.schemaRef("shop.domain.CartState")))
        val clash = contract.copyWith(
            contexts = listOf(context.copyWith(aggregates = listOf(cart, other))),
            defs = contract.defs + ("shop.domain.CartState" to contract.defs[CartState::class.java.name]),
        )
        assertThrows<IllegalStateException> { views(clash) }.message.assert()
            .contains("would both be viewed as shop.api.cart.CartStateView")
    }
}
