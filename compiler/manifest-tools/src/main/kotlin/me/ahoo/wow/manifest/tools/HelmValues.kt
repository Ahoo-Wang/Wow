package me.ahoo.wow.manifest.tools

import me.ahoo.wow.manifest.Manifest
import tools.jackson.module.kotlin.jacksonObjectMapper

/**
 * The values of the `wow-service` Helm chart that a service's build knows, its `service` block: the service's name, the
 * peers whose contracts are on its class path and the route its nodes serve the Manifest at. Everything else (the
 * image, the replicas, the resources, the stores and their credentials) is the deployment's own, in a values file
 * passed after this one.
 */
internal class HelmValues(val service: String, val peers: List<Peer>) {
    /** A peer [context], with the [service] its contract names: none when it names none. */
    data class Peer(val context: String, val service: String?)

    /** The values as YAML text: every string double-quoted, as JSON writes it, which YAML reads as it is. */
    fun yaml(): String = buildString {
        appendLine("# Generated by the Wow Gradle plugin (generateWowHelmValues) from the service's contract: the")
        appendLine("# values of the wow-service chart the build knows. Do not edit; pass this file to helm first and")
        appendLine("# the deployment's own values after it.")
        appendLine("service:")
        appendLine("  name: ${quoted(service)}")
        if (peers.isEmpty()) {
            appendLine("  peers: []")
        } else {
            appendLine("  peers:")
            peers.forEach { peer ->
                appendLine("    - context: ${quoted(peer.context)}")
                peer.service?.let { appendLine("      service: ${quoted(it)}") }
            }
        }
        appendLine("  manifest:")
        appendLine("    route: ${quoted(MANIFEST_ROUTE)}")
    }

    companion object {
        /** Where a node serves its Manifest, on either port (the HTTP edge's `GET /wow/manifest`). */
        const val MANIFEST_ROUTE: String = "/wow/manifest"

        private val mapper = jacksonObjectMapper()

        private fun quoted(text: String): String = mapper.writeValueAsString(text)

        /**
         * The values of the service of [manifest], its merged Manifest, whose peers are the contexts of the [contracts]
         * on its class path that it does not host, by context name, each once.
         */
        fun of(manifest: Manifest, contracts: List<Manifest>): HelmValues {
            val service = checkNotNull(manifest.service?.name) {
                "The service's Manifest names no service, so the chart's objects cannot be named after it."
            }
            val hosted = manifest.contexts.map { it.name }.toSet()
            val peers = contracts.flatMap { contract ->
                contract.contexts.map { Peer(it.name, contract.service?.name) }
            }.filter { it.context !in hosted }.distinctBy { it.context }.sortedBy { it.context }
            return HelmValues(service, peers)
        }
    }
}
