/**
 * Where a dataset client sends its queries: the dataset's bounded context and
 * name, and optionally a tenant prefix (`ResourceAttributionPathSpec.TENANT`,
 * whose `{tenantId}` the `urlParams` fill). `basePath` replaces
 * the computed `{attribution}/dataset/{context}/{dataset}` when given.
 */
export interface DatasetQueryClientOptions extends PartialBy<
  ApiMetadata,
  'basePath'
> {
  context: string;
  dataset: string;
  resourceAttribution?:
    ResourceAttributionPathSpec.NONE | ResourceAttributionPathSpec.TENANT;
}

/** `{attribution}/dataset/{context}/{dataset}`, the base path of a dataset's routes. */
export function datasetBasePath(
  context: string,
  dataset: string,
  resourceAttribution: ResourceAttributionPathSpec = ResourceAttributionPathSpec.NONE,
): string {
  const path = `dataset/${encodeURIComponent(context)}/${encodeURIComponent(dataset)}`;
  return resourceAttribution ? combineURLs(resourceAttribution, path) : path;
}

/**
 * A client for one dataset's query routes. It implements
 * {@link DatasetQueryApi}, the shape of a view-engine data source, so it can be
 * handed to the engine's `resources` as it is.
 *
 * @example
 * ```typescript
 * import { DatasetQueryClient, aggregation } from '@ahoo-wang/wow-client';
 *
 * const orders = new DatasetQueryClient({
 *   context: 'analytics',
 *   dataset: 'order_wide',
 * });
 * const byCity = await orders.aggregate(
 *   aggregation.query({
 *     groupBy: [aggregation.terms('city', 'city')],
 *     metrics: [aggregation.count('orders')],
 *   }),
 * );
 * ```
 */
@api()
export class DatasetQueryClient<
  R = DynamicDocument,
  FIELDS extends string = string,
>
  implements DatasetQueryApi<R, FIELDS>, ApiMetadataCapable
{
  public readonly apiMetadata: ApiMetadata;

  constructor(options: DatasetQueryClientOptions) {
    const { context, dataset, resourceAttribution, ...apiMetadata } = options;
    this.apiMetadata = {
      ...apiMetadata,
      basePath:
        options.basePath ??
        datasetBasePath(context, dataset, resourceAttribution),
    };
    bindMethods(this);
  }

  @post(DatasetQueryEndpointPaths.SINGLE)
  /* v8 ignore start */
  single<T extends Partial<R> = R>(
    @body() query: FilterSingleQuery<FIELDS>,
    @attribute() attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<T> {
    throw autoGeneratedError(query, attributes, abort);
  }
  /* v8 ignore stop */

  @post(DatasetQueryEndpointPaths.LIST)
  /* v8 ignore start */
  list<T extends Partial<R> = R>(
    @body() query: FilterListQuery<FIELDS>,
    @attribute() attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<T[]> {
    throw autoGeneratedError(query, attributes, abort);
  }
  /* v8 ignore stop */

  @post(DatasetQueryEndpointPaths.LIST, QUERY_STREAM_ENDPOINT)
  /* v8 ignore start */
  listStream<T extends Partial<R> = R>(
    @body() query: FilterListQuery<FIELDS>,
    @attribute() attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<ReadableStream<T>> {
    throw autoGeneratedError(query, attributes, abort);
  }
  /* v8 ignore stop */

  @post(DatasetQueryEndpointPaths.PAGED)
  /* v8 ignore start */
  paged<T extends Partial<R> = R>(
    @body() query: FilterPagedQuery<FIELDS>,
    @attribute() attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<PagedList<T>> {
    throw autoGeneratedError(query, attributes, abort);
  }
  /* v8 ignore stop */

  @post(DatasetQueryEndpointPaths.CURSOR)
  /* v8 ignore start */
  cursor<T extends Partial<R> = R>(
    @body() query: CursorQuery<FIELDS>,
    @attribute() attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<CursorPage<T>> {
    throw autoGeneratedError(query, attributes, abort);
  }
  /* v8 ignore stop */

  @post(DatasetQueryEndpointPaths.COUNT)
  /* v8 ignore start */
  count(
    @body() filter: FilterExpression<FIELDS>,
    @attribute() attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<number> {
    throw autoGeneratedError(filter, attributes, abort);
  }
  /* v8 ignore stop */

  @post(DatasetQueryEndpointPaths.AGGREGATION)
  /* v8 ignore start */
  aggregate<
    Row extends object = DynamicDocument,
    AGGREGATION_FIELDS extends string = string,
  >(
    @body() query: AggregationQuery<FIELDS, AGGREGATION_FIELDS>,
    @attribute() attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<Row[]> {
    throw autoGeneratedError(query, attributes, abort);
  }
  /* v8 ignore stop */

  @post(DatasetQueryEndpointPaths.AGGREGATION, QUERY_STREAM_ENDPOINT)
  /* v8 ignore start */
  aggregateStream<
    Row extends object = DynamicDocument,
    AGGREGATION_FIELDS extends string = string,
  >(
    @body() query: AggregationQuery<FIELDS, AGGREGATION_FIELDS>,
    @attribute() attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<ReadableStream<Row>> {
    throw autoGeneratedError(query, attributes, abort);
  }
  /* v8 ignore stop */

  async describe(
    previous?: string,
    attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<QueryDescriptorResult> {
    const version = descriptorVersion(previous);
    const exchange = await new DatasetDescriptorEndpoint(
      this.apiMetadata,
    ).schema(ifNoneMatch(version), attributes, abort);
    return readDescriptor(exchange, version);
  }
}
