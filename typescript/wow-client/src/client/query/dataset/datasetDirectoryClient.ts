import type {
  ApiMetadata,
  ApiMetadataCapable,
} from '@ahoo-wang/fetcher-decorator';
import {
  api,
  attribute,
  autoGeneratedError,
  get,
} from '@ahoo-wang/fetcher-decorator';
import { bindMethods } from '../../bindMethods.js';

/**
 * One dataset a service serves, as its directory lists it: where it is named,
 * its title, and the version of its capability descriptor, `null` while its
 * schema does not compile (its table contradicts its declaration, say).
 */
export interface DatasetDirectoryEntry {
  contextName: string;
  name: string;
  title: string | null;
  version: string | null;
}

/**
 * The dataset directory of a service (`GET /dataset`): every dataset it
 * serves, those published at run time included. A host reads it to offer
 * the datasets and to register each one with the view engine.
 *
 * @example
 * ```typescript
 * import { DatasetDirectoryClient } from '@ahoo-wang/wow-client';
 *
 * const datasets = await new DatasetDirectoryClient().list();
 * ```
 */
@api()
export class DatasetDirectoryClient implements ApiMetadataCapable {
  constructor(public readonly apiMetadata?: ApiMetadata) {
    bindMethods(this);
  }

  @get('dataset')
  /* v8 ignore start */
  list(
    @attribute() attributes?: Record<string, unknown>,
    abort?: AbortController | AbortSignal,
  ): Promise<DatasetDirectoryEntry[]> {
    throw autoGeneratedError(attributes, abort);
  }
  /* v8 ignore stop */
}
