// Generates src/manifestTypes.ts, the TypeScript types of the Manifest
// format, from the Manifest's own JSON Schema: `ManifestSchema` of
// :manifest, published as META-INF/wow/manifest.schema.json.
//
//   node typescript/wow-client/scripts/manifest-types.mjs
//
// test/manifestTypes.test.ts fails when the committed file is not what this
// writes, so a change to the format reaches the TypeScript types in the same
// pull request.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const PACKAGE = fileURLToPath(new URL('..', import.meta.url));
export const SCHEMA = join(
  PACKAGE,
  '../../api/manifest/src/main/resources/META-INF/wow/manifest.schema.json',
);
export const OUTPUT = join(PACKAGE, 'src/manifestTypes.ts');

/** The TypeScript name of the schema's definition `name`. */
function typeName(name) {
  return `${name}Manifest`;
}

function doc(description, indent) {
  return description ? `${indent}/** ${description} */\n` : '';
}

/** The TypeScript type of `schema`. */
function typeOf(schema) {
  if (schema.$ref) return typeName(schema.$ref.replace('#/$defs/', ''));
  if (schema.enum) {
    // A reader reads a value a newer writer added leniently: the union is open.
    return [...schema.enum.map(value => `'${value}'`), '(string & {})'].join(
      ' | ',
    );
  }
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'array':
      return `readonly ${wrap(typeOf(schema.items))}[]`;
    default:
      return schema.const !== undefined ? 'number' : 'unknown';
  }
}

function wrap(type) {
  return type.includes(' ') ? `(${type})` : type;
}

/** The interface `name` of the object schema `schema`. */
function interfaceOf(name, schema) {
  const required = new Set(schema.required ?? []);
  const members = Object.entries(schema.properties ?? {}).map(
    ([key, property]) => {
      const type =
        key === '$defs'
          ? 'Readonly<Record<string, Readonly<Record<string, unknown>>>>'
          : typeOf(property);
      const optional = required.has(key) ? '' : '?';
      return `${doc(property.description, '  ')}  readonly ${key}${optional}: ${type};`;
    },
  );
  return `${doc(schema.description ?? schema.title, '')}export interface ${name} {\n${members.join('\n')}\n}\n`;
}

/** The source of src/manifestTypes.ts for the Manifest schema `schema`, formatted. */
export async function manifestTypes(schema) {
  const header = `// Code generated by scripts/manifest-types.mjs from the Manifest's JSON
// Schema (ManifestSchema of :manifest, META-INF/wow/manifest.schema.json).
// DO NOT EDIT: change ManifestSchema and run the script.
`;
  const definitions = Object.entries(schema.$defs).map(([name, definition]) =>
    interfaceOf(typeName(name), definition),
  );
  const source = [header, interfaceOf('Manifest', schema), ...definitions].join(
    '\n',
  );
  const options = (await prettier.resolveConfig(OUTPUT)) ?? {};
  return prettier.format(source, { ...options, filepath: OUTPUT });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(
    OUTPUT,
    await manifestTypes(JSON.parse(readFileSync(SCHEMA, 'utf8'))),
  );
  console.log(`Wrote ${OUTPUT}`);
}
