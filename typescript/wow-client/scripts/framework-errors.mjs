// Generates src/frameworkErrors.ts, the framework's error codes, what a
// retry of each may do and the default retry policy, from the error catalog:
// `FrameworkErrors` of :manifest, written by its FrameworkErrorsTest as
// api/manifest/src/test/resources/framework-errors.json.
//
//   node typescript/wow-client/scripts/framework-errors.mjs
//
// test/frameworkErrors.test.ts fails when the committed file is not what this
// writes, so a change to the catalog reaches the TypeScript client in the
// same pull request.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const PACKAGE = fileURLToPath(new URL('..', import.meta.url));
export const CATALOG = join(
  PACKAGE,
  '../../api/manifest/src/test/resources/framework-errors.json',
);
export const OUTPUT = join(PACKAGE, 'src/frameworkErrors.ts');

const doc = text => `/** ${text.replaceAll('*/', '*\\/')} */`;

/** The source of src/frameworkErrors.ts for `catalog`, formatted. */
export async function frameworkErrors(catalog) {
  const { retry, errors } = catalog;
  const source = `// Code generated by scripts/framework-errors.mjs from the error catalog
// (FrameworkErrors of :manifest, api/manifest/src/test/resources/framework-errors.json).
// DO NOT EDIT: change FrameworkErrors and run the script.

/**
 * What a retry of a request answered with an error may do, as the error
 * catalog declares it for the error's code and every problem carries it
 * (\`retry\`): \`none\`, a retry fails alike; \`same-request\`, send it again
 * with the same request id (\`Wow-Request-Id\`), so a command that did commit
 * is answered as its duplicate; \`new-request\`, send it again as it is.
 */
export type Retry = 'none' | 'same-request' | 'new-request';

/**
 * The framework's error codes, each answered with the status of the error
 * catalog. A domain rejection has a code of its own, answered with 422 unless
 * the service configures another status.
 */
export const FrameworkErrorCodes = {
${errors
  .map(
    error =>
      `  ${doc(`${error.status} ${error.title}: ${error.description ?? ''}`.trim())}\n  ${error.name}: '${error.code}',`,
  )
  .join('\n')}
} as const;

/** A {@link FrameworkErrorCodes} value. */
export type FrameworkErrorCode =
  (typeof FrameworkErrorCodes)[keyof typeof FrameworkErrorCodes];

/** What a retry of a framework code may do, as the error catalog declares it. */
export interface FrameworkRetry {
  /** What a retry may do: never \`none\` here. */
  readonly retry: Retry;
  /** Its \`Retry-After\`, in milliseconds. */
  readonly retryAfterMs: number;
}

/**
 * What a retry may do of each framework code a retry may get past, by code;
 * a retry of every other code, a domain's among them, is \`none\`.
 */
export const FRAMEWORK_RETRIES: ReadonlyMap<string, FrameworkRetry> = new Map<
  string,
  FrameworkRetry
>([
${errors
  .filter(error => error.retry !== 'none')
  .map(
    error =>
      `  ['${error.code}', { retry: '${error.retry}', retryAfterMs: ${error.retryAfter * 1000} }],`,
  )
  .join('\n')}
]);

/**
 * How often, and after how long, a client sends a request again by default
 * when a retry may get past its error, as the Kotlin client does
 * (\`RetryPolicy.DEFAULT\`): at most \`attempts\` attempts, the first included,
 * \`backoffMs\` before the first retry without a \`Retry-After\`, doubled at each
 * attempt up to \`maxWaitMs\`.
 */
export const DEFAULT_RETRY = {
  attempts: ${retry.attempts},
  backoffMs: ${retry.backoffMillis},
  maxWaitMs: ${retry.maxWaitSeconds * 1000},
} as const;
`;
  const options = (await prettier.resolveConfig(OUTPUT)) ?? {};
  return prettier.format(source, { ...options, filepath: OUTPUT });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(
    OUTPUT,
    await frameworkErrors(JSON.parse(readFileSync(CATALOG, 'utf8'))),
  );
  console.log(`Wrote ${OUTPUT}`);
}
