/** Read-only data at an extension boundary, including nested arrays and objects. */
export type DeepReadonly<T> = unknown extends T
  ? T
  : T extends (...args: never[]) => unknown
    ? T
    : T extends readonly (infer Item)[]
      ? readonly DeepReadonly<Item>[]
      : T extends object
        ? { readonly [Key in keyof T]: DeepReadonly<T[Key]> }
        : T;

/** A structured clone is an independent, writable DTO; the source remains readonly. */
export function cloneSnapshot<T>(value: DeepReadonly<T>): T {
  return structuredClone(value) as T;
}
