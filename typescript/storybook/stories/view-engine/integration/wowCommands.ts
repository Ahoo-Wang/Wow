import type { Fetcher } from '@ahoo-wang/fetcher';
import { CommandGateway, wait } from '@ahoo-wang/wow-client';
import type { OrderCommands } from './orderActions.js';

// Step 4b: the commands, sent to the Wow service. A command client
// generated by wow-generator types each route and body; this one sends
// them by path.
export function wowOrderCommands(fetcher: Fetcher): OrderCommands {
  const gateway = new CommandGateway({ fetcher });
  // Answer once the snapshot is written: the engine reads the view again
  // right after `run` resolves, and must see the command's result.
  const send = async (orderId: string, command: string) => {
    // A refused command rejects (a `WowProblemError`): the engine reports
    // it on that order, and the order stays selected.
    await gateway.wait({
      command: `example.order.${command}`,
      id: orderId,
      wait: [wait.snapshot('example')],
    });
  };
  return {
    ship: orderId => send(orderId, 'ShipOrder'),
    cancel: orderId => send(orderId, 'CancelOrder'),
  };
}
